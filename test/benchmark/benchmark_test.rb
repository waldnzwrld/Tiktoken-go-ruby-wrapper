# frozen_string_literal: true

require_relative '../../tiktoken-encoder/lib/tiktoken/encoder'
require_relative '../helper'
require 'ffi'
require 'benchmark'
require 'memory_profiler'

class BenchmarkTest
  def benchmark(runs = 50_000, &block)
    # do not allow the block to be a call to go_profile
    return unless block_given?

    time = Benchmark.realtime do
      runs.times(&block)
    end
    puts "Total time taken for 50000 iterations: #{time} seconds"
    puts "Average time per iteration: #{time / 50_000} seconds"
  end

  def ruby_profile(runs = 50_000, &block)
    # do not allow the block to be a call to go_profile
    # this will cause a segfault
    return unless block_given?

    MemoryProfiler.start
    runs.times(&block)
    report = MemoryProfiler.stop
    report.pretty_print
  end

  def test_over_time(runs = 100, &block)
    return unless block_given?

    i = 0
    while i < 100
      runs.times(&block)
      p "#{i + 1} successful runs"
      i += 1
    end
  end
end

benchmarker = BenchmarkTest.new
test_string = Helper::FOUR_K_STRING
encoding = 'cl100k_base'
encoder = TikToken::Encoder.new(encoding)

benchmarker.benchmark do
  encoder.encode_string(test_string)
end

benchmarker.ruby_profile do
  encoder.encode_string(test_string)
end

encoder.free_encoder

# this performs every cgo function call
# that is exposed to this gem where the encode
# function is performed in a loop for the number of runs
# a pprof file is generated by this function
n = FFI::MemoryPointer.new(:long)
TikToken::Encoder.goProfile('gpt-4', test_string, n, 1000)
