# frozen_string_literal: true

require_relative "../../lib/tiktoken"
require_relative "../helpers/helper"
require "memory_profiler"

class ProfileTest
  def ruby_profile(runs = 50000, &block)
    # do not allow the block to be a call to go_profile
    # this will cause a segfault
    return unless block_given?

    MemoryProfiler.start
    runs.times(&block)
    report = MemoryProfiler.stop
  end

  def go_profile
    # this performs every cgo function call
    # that is exposed to this gem where the encode
    # function is performed in a loop for the number of runs
    # a pprof file is generated by this function
    # This pprof is pertinent to the GO side of things
    n = Fiddle::Pointer.malloc(Fiddle::SIZEOF_LONG)
    Tiktoken::Encoder.goProfile("gpt-4", test_string, n, 15000, 0)
    Fiddle.free(n)
    return
  end

  def test_string
    @test_string ||= Helper::FOUR_H_STRING
  end

  def encoder
    @encoder ||= Tiktoken::Encoder.new("cl100k_base")
  end

  def run_memory_profiler
    results = ruby_profile do
      encoder.encode_string(text: test_string)
    end

    return results.pretty_print(detailed_report: true)
  end

  def test_over_time(runs = 100, &block)
    return unless block_given?

    i = 0
    while i < 100
      runs.times(&block)
      p "#{i + 1} successful runs"
      i += 1
    end
  end
end
